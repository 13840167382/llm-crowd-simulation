            scheduler.RegisterAgentReporter(this);

            DecisionAgentRequestDto request;
            string error;
            var isValid = TryBuildDecisionRequest(out request, out error);
            scheduler.ReportAgentState(this, request, needsLlmDecision, isValid, error);

            lastReportAtUnixMs = RequestIdUtility.GetUnixTimestampMs();
            lastReportMessage = isValid
                ? "Reported agent state. needs_decision=" + needsLlmDecision
                : "Reported invalid agent state. error=" + error;

            nextReportAtTime = Time.unscaledTime + Mathf.Max(0.1f, reportIntervalSeconds);
        }

