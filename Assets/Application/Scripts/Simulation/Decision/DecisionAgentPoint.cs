            if (disableNavMeshInZone && !string.IsNullOrWhiteSpace(currentZoneId))
            {
                SetNavMeshEnabled(false);
            }

            TryApplyInitialWaitingGate();
            SyncRendererVisibilityByCurrentZone();

            if (scheduler != null)
            {
                scheduler.RegisterAgentReporter(this);
            }

            nextReportAtTime = Time.unscaledTime + Mathf.Max(0.1f, reportIntervalSeconds);

            if (enableLegacySelfReporting && reportOnEnable)
            {
                ReportToSchedulerNow();
            }
        }

