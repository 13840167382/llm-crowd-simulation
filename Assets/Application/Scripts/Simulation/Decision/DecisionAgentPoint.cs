        private bool IsDecisionResultForThisAgent(string resultAgentId)
        {
            var normalizedSelfAgentId = string.IsNullOrWhiteSpace(agentId) ? string.Empty : agentId.Trim();
            if (string.IsNullOrWhiteSpace(normalizedSelfAgentId) || string.IsNullOrWhiteSpace(resultAgentId))
            {
                return false;
            }

            if (string.Equals(normalizedSelfAgentId, resultAgentId, StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }

            var markerIndex = resultAgentId.LastIndexOf('#');
            if (markerIndex <= 0 || markerIndex >= resultAgentId.Length - 1)
            {
                return false;
            }

            var resultBaseAgentId = resultAgentId.Substring(0, markerIndex).Trim();
            if (!string.Equals(normalizedSelfAgentId, resultBaseAgentId, StringComparison.OrdinalIgnoreCase))
            {
                return false;
            }

            var resultInstanceToken = resultAgentId.Substring(markerIndex + 1).Trim();
            if (string.IsNullOrWhiteSpace(resultInstanceToken))
            {
                return false;
            }

            return string.Equals(resultInstanceToken, GetInstanceID().ToString(), StringComparison.Ordinal);
        }

        private void ResolveNavMeshAgent()
        {
            if (navMeshAgent != null)
            {
                return;
            }

            if (!autoFindNavMeshAgent)
            {
                return;
            }

            navMeshAgent = GetComponent<NavMeshAgent>();
        }

        private void ResetInitialWaitingGateState()
        {
            hasReceivedFirstDecision = false;
            initialWaitingGateActive = false;
            cachedRenderers = Array.Empty<Renderer>();
            cachedRendererEnabledStates = Array.Empty<bool>();
            hasCachedRendererStates = false;
        }

        private void CacheRendererStatesIfNeeded()
        {
            if (hasCachedRendererStates)
            {
                return;
            }

            cachedRenderers = GetComponentsInChildren<Renderer>(true) ?? Array.Empty<Renderer>();
            cachedRendererEnabledStates = new bool[cachedRenderers.Length];
            for (var i = 0; i < cachedRenderers.Length; i++)
            {
                var rendererComponent = cachedRenderers[i];
                cachedRendererEnabledStates[i] = rendererComponent != null && rendererComponent.enabled;
            }

            hasCachedRendererStates = true;
        }

        private void SetRenderersVisible(bool visible)
        {
            CacheRendererStatesIfNeeded();

            for (var i = 0; i < cachedRenderers.Length; i++)
            {
                var rendererComponent = cachedRenderers[i];
                if (rendererComponent == null)
                {
                    continue;
                }

                if (!visible)
                {
                    rendererComponent.enabled = false;
                    continue;
                }

                rendererComponent.enabled = i < cachedRendererEnabledStates.Length
                    ? cachedRendererEnabledStates[i]
                    : true;
            }
        }

        private void TryApplyInitialWaitingGate()
        {
            if (!Application.isPlaying
                || !hideAndDisableUntilFirstDecision
                || hasReceivedFirstDecision
                || !needsLlmDecision
                || hasPendingExitPosition
                || hasPendingNavmeshTargetPosition)
            {
                return;
            }

            if (initialWaitingGateActive)
            {
                return;
            }

            SetRenderersVisible(false);
            SetNavMeshEnabled(false);
            initialWaitingGateActive = true;
            lastMoveMessage = "Initial waiting: navmesh and renderers disabled until first decision.";
        }

        private void ReleaseInitialWaitingGateForFirstDecision()
        {
            if (hasReceivedFirstDecision)
            {
                return;
            }

            hasReceivedFirstDecision = true;

            if (!hideAndDisableUntilFirstDecision)
            {
                return;
            }

            if (!initialWaitingGateActive)
            {
                return;
            }

            SetRenderersVisible(true);
            SetNavMeshEnabled(true);
            initialWaitingGateActive = false;
            SyncRendererVisibilityByCurrentZone();
            lastMoveMessage = "First decision received: navmesh and renderers enabled.";
        }

        private void RestoreRenderersIfNeeded()
        {
            if (!initialWaitingGateActive)
            {
                return;
            }

            SetRenderersVisible(true);
            initialWaitingGateActive = false;
        }

        private bool IsCurrentlyOnNavMesh()
        {
            ResolveNavMeshAgent();
            return navMeshAgent != null
                && navMeshAgent.enabled
                && navMeshAgent.isOnNavMesh;
        }

        private void ClearNavMeshPathIfAny()
        {
            ResolveNavMeshAgent();
            if (navMeshAgent == null || !navMeshAgent.enabled)
            {
                return;
            }

            if (navMeshAgent.pathPending || navMeshAgent.hasPath || navMeshAgent.velocity.sqrMagnitude > 0.0001f)
            {
                navMeshAgent.ResetPath();
            }
        }

        private bool TryMoveToLlmChosenExit(string chosenExitId)
        {
            if (!moveByLlmExitDecision)
            {
                ClearPendingMoveTargets();
                ClearNavMeshPathIfAny();
                lastMoveMessage = "Move skipped: moveByLlmExitDecision is disabled.";
                return false;
            }

            var normalizedExitId = string.IsNullOrWhiteSpace(chosenExitId) ? string.Empty : chosenExitId.Trim();
            if (string.IsNullOrWhiteSpace(normalizedExitId))
            {
                ClearPendingMoveTargets();
                ClearNavMeshPathIfAny();
                lastMoveMessage = "Move skipped: chosen exit id is empty.";
                return false;
            }

            ResolveTopologySceneConfig();
            if (topologySceneConfig == null)
            {
                ClearPendingMoveTargets();
                ClearNavMeshPathIfAny();
                lastMoveMessage = "Move skipped: TopologySceneConfig is missing.";
                return false;
            }

            string resolvedTargetZoneId;
            string resolvedBy;
            if (!TryResolveChosenTargetZoneId(normalizedExitId, out resolvedTargetZoneId, out resolvedBy))
            {
                ClearPendingMoveTargets();
                ClearNavMeshPathIfAny();
                lastMoveMessage = "Move skipped: cannot resolve chosen id to target zone. chosen_id=" + normalizedExitId;
                return false;
            }

            var normalizedCurrentZoneId = string.IsNullOrWhiteSpace(currentZoneId)
                ? string.Empty
                : currentZoneId.Trim();

            if (string.IsNullOrWhiteSpace(normalizedCurrentZoneId))
            {
                ClearPendingMoveTargets();
                ClearNavMeshPathIfAny();
                lastMoveMessage = "Move skipped: current zone id is empty.";
                return false;
            }

            if (string.Equals(resolvedTargetZoneId, normalizedCurrentZoneId, StringComparison.OrdinalIgnoreCase))
            {
                ClearPendingMoveTargets();
                ClearNavMeshPathIfAny();
                if (disableNavMeshInZone && !IsCurrentlyOnNavMesh())
                {
                    SetNavMeshEnabled(false);
                }

                lastMoveMessage = "Move skipped: target zone equals current zone. keep position. zone_id=" + normalizedCurrentZoneId;
                return true;
            }

            TopologyExitDto entryExit;
            float entryDistance;
            if (!topologySceneConfig.TryGetNearestExitBySourceZone(normalizedCurrentZoneId, transform.position, out entryExit, out entryDistance)
                || entryExit == null
                || string.IsNullOrWhiteSpace(entryExit.exit_id)
                || entryExit.position == null)
            {
                ClearPendingMoveTargets();
                ClearNavMeshPathIfAny();
                lastMoveMessage = "Move skipped: cannot find current-zone connector exit. current_zone_id=" + normalizedCurrentZoneId;
                return false;
            }

            var entryExitPosition = new Vector3(entryExit.position.x, transform.position.y, entryExit.position.z);

            TopologyExitDto targetZoneExit;
            float targetDistance;
            if (!topologySceneConfig.TryGetNearestExitBySourceZone(resolvedTargetZoneId, entryExitPosition, out targetZoneExit, out targetDistance)
                || targetZoneExit == null
                || string.IsNullOrWhiteSpace(targetZoneExit.exit_id)
                || targetZoneExit.position == null)
            {
                ClearPendingMoveTargets();
                ClearNavMeshPathIfAny();
                lastMoveMessage = "Move skipped: cannot find target-zone connector exit. target_zone_id=" + resolvedTargetZoneId;
                return false;
            }

            pendingExitId = entryExit.exit_id.Trim();
            pendingExitPosition = entryExitPosition;
            hasPendingExitPosition = true;
            pendingNavmeshTargetExitId = targetZoneExit.exit_id.Trim();
            pendingNavmeshTargetPosition = new Vector3(targetZoneExit.position.x, transform.position.y, targetZoneExit.position.z);
            hasPendingNavmeshTargetPosition = true;
            pendingTargetZoneId = resolvedTargetZoneId;
            movingToExitBeforeNavMesh = false;

            var currentPos = new Vector2(transform.position.x, transform.position.z);
            var outputPos = new Vector2(pendingNavmeshTargetPosition.x, pendingNavmeshTargetPosition.z);
            const float samePositionDistance = 0.02f;
            if (Vector2.Distance(currentPos, outputPos) <= samePositionDistance)
            {
                ClearPendingMoveTargets();
                ClearNavMeshPathIfAny();
                if (disableNavMeshInZone && !IsCurrentlyOnNavMesh())
                {
                    SetNavMeshEnabled(false);
                }

                lastMoveMessage = "Move skipped: output position equals current position. keep position.";
                return true;
            }

            if (preMoveToExitBeforeEnableNavMesh && !IsCurrentlyOnNavMesh())
            {
                SetNavMeshEnabled(false);
                movingToExitBeforeNavMesh = true;
                EnsureRenderersVisibleForMovementStart();
                lastMoveMessage = "Moving inside zone before navmesh handoff. chosen_id=" + normalizedExitId
                    + ", resolved_by=" + resolvedBy
                    + ", entry_exit_id=" + pendingExitId
                    + ", navmesh_target_exit_id=" + pendingNavmeshTargetExitId
                    + ", target_zone_id=" + pendingTargetZoneId
                    + ", entry_distance=" + entryDistance.ToString("F2")
                    + ", target_distance=" + targetDistance.ToString("F2");
                return true;
            }

            if (TryStartNavMeshMoveToPendingNavmeshTarget())
            {
                EnsureRenderersVisibleForMovementStart();
                lastMoveMessage = "Moving by navmesh to target zone connector. chosen_id=" + normalizedExitId
                    + ", resolved_by=" + resolvedBy
                    + ", entry_exit_id=" + pendingExitId
                    + ", navmesh_target_exit_id=" + pendingNavmeshTargetExitId
                    + ", target_zone_id=" + pendingTargetZoneId
                    + ", destination=(" + pendingNavmeshTargetPosition.x.ToString("F2")
                    + ", " + pendingNavmeshTargetPosition.z.ToString("F2") + ")";
                return true;
            }

            if (!IsCurrentlyOnNavMesh())
            {
                SetNavMeshEnabled(false);
                movingToExitBeforeNavMesh = true;
                EnsureRenderersVisibleForMovementStart();
                lastMoveMessage = "NavMesh unavailable, fallback to direct move to entry exit. chosen_id=" + normalizedExitId
                    + ", entry_exit_id=" + pendingExitId
                    + ", navmesh_target_exit_id=" + pendingNavmeshTargetExitId;
                return true;
            }

            movingToExitBeforeNavMesh = false;
            ClearNavMeshPathIfAny();
            lastMoveMessage = "Move deferred: failed to set new navmesh target while already on navmesh. keep navmesh enabled."
                + " chosen_id=" + normalizedExitId
                + ", entry_exit_id=" + pendingExitId
                + ", navmesh_target_exit_id=" + pendingNavmeshTargetExitId;
            return true;
        }

        private bool TryResolveChosenTargetZoneId(string chosenId, out string targetZoneId, out string resolvedBy)
        {
            targetZoneId = string.Empty;
            resolvedBy = "none";

            var normalizedChosenId = string.IsNullOrWhiteSpace(chosenId) ? string.Empty : chosenId.Trim();
            var normalizedCurrentZoneId = string.IsNullOrWhiteSpace(currentZoneId) ? string.Empty : currentZoneId.Trim();
            if (string.IsNullOrWhiteSpace(normalizedChosenId))
            {
                return false;
            }

            ResolveTopologySceneConfig();
            if (topologySceneConfig == null)
            {
                return false;
            }

            TopologyZoneDto chosenZone;
            if (topologySceneConfig.TryGetZoneById(normalizedChosenId, out chosenZone)
                && chosenZone != null
                && !string.IsNullOrWhiteSpace(chosenZone.zone_id))
            {
                var resolvedZoneId = chosenZone.zone_id.Trim();
                if (string.IsNullOrWhiteSpace(normalizedCurrentZoneId)
                    || !string.Equals(resolvedZoneId, normalizedCurrentZoneId, StringComparison.OrdinalIgnoreCase))
                {
                    targetZoneId = resolvedZoneId;
                    resolvedBy = "zone_id";
                    return true;
                }
            }

            var options = BuildAvailableExits();
            for (var i = 0; i < options.Count; i++)
            {
                var option = options[i];
                if (option == null
                    || string.IsNullOrWhiteSpace(option.exit_id)
                    || !string.Equals(option.exit_id, normalizedChosenId, StringComparison.OrdinalIgnoreCase)
                    || string.IsNullOrWhiteSpace(option.target_zone_id))
                {
                    continue;
                }

                var optionTargetZoneId = option.target_zone_id.Trim();
                if (!string.IsNullOrWhiteSpace(normalizedCurrentZoneId)
                    && string.Equals(optionTargetZoneId, normalizedCurrentZoneId, StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }

                targetZoneId = optionTargetZoneId;
                resolvedBy = "request_option.target_zone_id";
                return true;
            }

            TopologyExitDto chosenExit;
            if (topologySceneConfig.TryGetExitById(normalizedChosenId, out chosenExit)
                && chosenExit != null)
            {
                var sourceZoneId = string.IsNullOrWhiteSpace(chosenExit.source_zone_id)
                    ? string.Empty
                    : chosenExit.source_zone_id.Trim();
                var targetZoneIdCandidate = string.IsNullOrWhiteSpace(chosenExit.target_zone_id)
                    ? string.Empty
                    : chosenExit.target_zone_id.Trim();

                string fallbackZoneId = string.Empty;
                if (!string.IsNullOrWhiteSpace(normalizedCurrentZoneId))
                {
                    if (string.Equals(sourceZoneId, normalizedCurrentZoneId, StringComparison.OrdinalIgnoreCase)
                        && !string.IsNullOrWhiteSpace(targetZoneIdCandidate))
                    {
                        fallbackZoneId = targetZoneIdCandidate;
                    }
                    else if (string.Equals(targetZoneIdCandidate, normalizedCurrentZoneId, StringComparison.OrdinalIgnoreCase)
                        && !string.IsNullOrWhiteSpace(sourceZoneId))
                    {
                        fallbackZoneId = sourceZoneId;
                    }
                }

                if (string.IsNullOrWhiteSpace(fallbackZoneId))
                {
                    fallbackZoneId = !string.IsNullOrWhiteSpace(targetZoneIdCandidate)
                        ? targetZoneIdCandidate
                        : sourceZoneId;
                }

                if (!string.IsNullOrWhiteSpace(fallbackZoneId))
                {
                    targetZoneId = fallbackZoneId.Trim();
                    resolvedBy = "exit_id_fallback";
                    return true;
                }
            }

            return false;
        }

        private bool TryStartNavMeshMoveToPendingNavmeshTarget()
        {
            if (!hasPendingNavmeshTargetPosition)
            {
                navPathPendingDurationSeconds = 0f;
                return false;
            }

            ResolveNavMeshAgent();
            if (navMeshAgent == null)
            {
                navPathPendingDurationSeconds = 0f;
                return false;
            }

            if (!TryPrepareNavMeshAtCurrentPosition())
            {
                navPathPendingDurationSeconds = 0f;
                return false;
            }

            var destination = pendingNavmeshTargetPosition;
            NavMeshHit navMeshHit;
            if (NavMesh.SamplePosition(destination, out navMeshHit, Mathf.Max(0.1f, navMeshSampleRadius), NavMesh.AllAreas))
            {
                destination = navMeshHit.position;
            }

            pendingNavmeshTargetPosition = destination;

            if (!navMeshAgent.SetDestination(destination))
            {
                navPathPendingDurationSeconds = 0f;
                return false;
            }

            navPathPendingDurationSeconds = 0f;

            return true;
        }

        private void TryRecoverFromPersistentPathPending()
        {
            if (!hasPendingNavmeshTargetPosition)
            {
                navPathPendingDurationSeconds = 0f;
                return;
            }

            ResolveNavMeshAgent();
            if (navMeshAgent == null || !navMeshAgent.enabled || !navMeshAgent.isOnNavMesh)
            {
                navPathPendingDurationSeconds = 0f;
                return;
            }

            if (!navMeshAgent.pathPending)
            {
                navPathPendingDurationSeconds = 0f;
                return;
            }

            navPathPendingDurationSeconds += Mathf.Max(0f, Time.deltaTime);
            if (navPathPendingDurationSeconds < Mathf.Max(0.2f, pathPendingRetrySeconds))
            {
                return;
            }

            navMeshAgent.ResetPath();
            navPathPendingDurationSeconds = 0f;

            if (TryStartNavMeshMoveToPendingNavmeshTarget())
            {
                lastMoveMessage = "PathPending timeout, retried navmesh destination. target_exit_id=" + pendingNavmeshTargetExitId;
                return;
            }

            if (hasPendingExitPosition)
            {
                SetNavMeshEnabled(false);
                movingToExitBeforeNavMesh = true;
                lastMoveMessage = "PathPending timeout, fallback to pre-move before navmesh handoff. entry_exit_id=" + pendingExitId
                    + ", target_exit_id=" + pendingNavmeshTargetExitId;
            }
        }

        private void TryAdvanceZoneToExitMove()
        {
            if (!movingToExitBeforeNavMesh || !hasPendingExitPosition)
            {
                return;
            }

            if (IsCurrentlyOnNavMesh())
            {
                movingToExitBeforeNavMesh = false;
                if (hasPendingNavmeshTargetPosition
                    && navMeshAgent != null
                    && !navMeshAgent.pathPending
                    && !navMeshAgent.hasPath)
                {
                    TryStartNavMeshMoveToPendingNavmeshTarget();
                }

                return;
            }

            var target = pendingExitPosition;
            target.y = transform.position.y;

            var speed = Mathf.Max(0.1f, zoneToExitMoveSpeed);
            transform.position = Vector3.MoveTowards(transform.position, target, speed * Time.deltaTime);

            var handoffDistance = Mathf.Max(zoneToExitNavMeshHandoffDistance, exitArriveDistance);
            if (Vector3.Distance(transform.position, target) > handoffDistance)
            {
                return;
            }

            if (TryStartNavMeshMoveToPendingNavmeshTarget())
            {
                movingToExitBeforeNavMesh = false;
                lastMoveMessage = "Reached entry exit handoff area, navmesh enabled. entry_exit_id=" + pendingExitId
                    + ", navmesh_target_exit_id=" + pendingNavmeshTargetExitId;
            }
        }

        private void TryApplyPendingZoneAfterArrived()
        {
            if (string.IsNullOrWhiteSpace(pendingTargetZoneId)
                || string.IsNullOrWhiteSpace(pendingExitId)
                || (!hasPendingExitPosition && !hasPendingNavmeshTargetPosition))
            {
                return;
            }

            var agentPos = new Vector2(transform.position.x, transform.position.z);
            var finalExitPosition = hasPendingNavmeshTargetPosition ? pendingNavmeshTargetPosition : pendingExitPosition;
            var exitPos = new Vector2(finalExitPosition.x, finalExitPosition.z);
            var arriveDistance = Mathf.Max(0.05f, exitArriveDistance);
            if (Vector2.Distance(agentPos, exitPos) > arriveDistance)
            {
                return;
            }

            SetNavMeshEnabled(false);

            var movedToZoneArea = false;
            var targetZoneId = pendingTargetZoneId;
            ResolveTopologySceneConfig();
            if (topologySceneConfig != null
                && topologySceneConfig.TryGetRandomPointInZone(
                    targetZoneId,
                    transform.position.y,
                    Mathf.Max(0f, zoneSpawnPadding),
                    out var zonePosition))
            {
                transform.position = zonePosition;
                movedToZoneArea = true;
            }

            SetCurrentZone(targetZoneId);
            topologySceneConfig?.NotifyAgentArrivedToZone(currentZoneId);
            SyncRendererVisibilityByCurrentZone();
            var arrivedCount = topologySceneConfig != null
                ? topologySceneConfig.GetZoneArrivedCount(currentZoneId)
                : 0;

            var arrivedFromEntryExitId = pendingExitId;
            var arrivedAtTargetExitId = pendingNavmeshTargetExitId;
            ClearPendingMoveTargets();

            lastMoveMessage = movedToZoneArea
                ? "Arrived at target connector and entered zone area. current_zone_id=" + currentZoneId
                    + ", zone_arrived_count=" + arrivedCount
                    + ", entry_exit_id=" + arrivedFromEntryExitId
                    + ", target_exit_id=" + arrivedAtTargetExitId
                : "Arrived at target connector and switched zone. current_zone_id=" + currentZoneId
                    + ", zone_arrived_count=" + arrivedCount
                    + ", entry_exit_id=" + arrivedFromEntryExitId
                    + ", target_exit_id=" + arrivedAtTargetExitId;

            TryReportAfterStateChanged();
        }

        private bool TryPrepareNavMeshAtCurrentPosition()
        {
            ResolveNavMeshAgent();
            if (navMeshAgent == null)
            {
                return false;
            }

            Vector3 sampledPosition;
            if (!TrySampleNearestNavMeshPosition(transform.position, out sampledPosition))
            {
                if (navMeshAgent.enabled)
                {
                    navMeshAgent.ResetPath();
                    navMeshAgent.enabled = false;
                }

                return false;
            }

            transform.position = sampledPosition;

            if (!navMeshAgent.enabled)
            {
                navMeshAgent.enabled = true;
            }

            navMeshAgent.Warp(sampledPosition);
            if (!navMeshAgent.isOnNavMesh)
            {
                navMeshAgent.enabled = false;
                return false;
            }

            return true;
        }

        private bool TrySampleNearestNavMeshPosition(Vector3 sourcePosition, out Vector3 sampledPosition)
        {
            NavMeshHit navMeshHit;
            var primaryRadius = Mathf.Max(0.1f, navMeshSampleRadius);
            if (NavMesh.SamplePosition(sourcePosition, out navMeshHit, primaryRadius, NavMesh.AllAreas))
            {
                sampledPosition = navMeshHit.position;
                return true;
            }

            var fallbackRadius = Mathf.Max(primaryRadius, navMeshFallbackSampleRadius);
            if (fallbackRadius > primaryRadius + 0.01f
                && NavMesh.SamplePosition(sourcePosition, out navMeshHit, fallbackRadius, NavMesh.AllAreas))
            {
                sampledPosition = navMeshHit.position;
                return true;
            }

            sampledPosition = sourcePosition;
            return false;
        }

        private void SetNavMeshEnabled(bool enabled)
        {
            ResolveNavMeshAgent();
            if (navMeshAgent == null)
            {
                navPathPendingDurationSeconds = 0f;
                return;
            }

            if (!enabled)
            {
                if (navMeshAgent.enabled)
                {
                    navMeshAgent.ResetPath();
                    navMeshAgent.enabled = false;
                }

                navPathPendingDurationSeconds = 0f;

                return;
            }

            if (!navMeshAgent.enabled)
            {
                if (!TryPrepareNavMeshAtCurrentPosition())
                {
                    navPathPendingDurationSeconds = 0f;
                    return;
                }
            }
            else if (!navMeshAgent.isOnNavMesh)
            {
                if (!TryPrepareNavMeshAtCurrentPosition())
                {
                    navPathPendingDurationSeconds = 0f;
                    return;
                }
            }

            if (!navMeshAgent.pathPending)
            {
                navPathPendingDurationSeconds = 0f;
            }
        }

        private void ClearPendingMoveTargets()
        {
            pendingExitId = string.Empty;
            pendingNavmeshTargetExitId = string.Empty;
            hasPendingExitPosition = false;
            hasPendingNavmeshTargetPosition = false;
            movingToExitBeforeNavMesh = false;
            pendingTargetZoneId = string.Empty;
            navPathPendingDurationSeconds = 0f;
        }

        private void TrackBehaviorDebug()
        {
            if (!enableBehaviorDebugLogs || !Application.isPlaying)
            {
                return;
            }

            if (ShouldSuppressBehaviorDebugLogs())
            {
                return;
            }

            var currentPosition = transform.position;
            if (!hasDebugSamplePosition)
            {
                hasDebugSamplePosition = true;
                lastDebugSamplePosition = currentPosition;
                stationaryDurationSeconds = 0f;
                return;
            }

            var movedDistance = Vector3.Distance(lastDebugSamplePosition, currentPosition);
            if (movedDistance <= Mathf.Max(0.001f, debugStationaryDistanceEpsilon))
            {
                stationaryDurationSeconds += Mathf.Max(0f, Time.deltaTime);
            }
            else
            {
                stationaryDurationSeconds = 0f;
            }

            lastDebugSamplePosition = currentPosition;

            if (Time.unscaledTime < nextBehaviorDebugAtTime)
            {
                return;
            }

            var shouldLog = stationaryDurationSeconds >= Mathf.Max(0.5f, stationaryWarnThresholdSeconds)
                || needsLlmDecision
                || hasPendingExitPosition
                || hasPendingNavmeshTargetPosition
                || movingToExitBeforeNavMesh;
            if (!shouldLog)
            {
                return;
            }

            nextBehaviorDebugAtTime = Time.unscaledTime + Mathf.Max(0.2f, behaviorDebugLogIntervalSeconds);
            var snapshot = BuildBehaviorDebugSnapshot();
            if (stationaryDurationSeconds >= Mathf.Max(0.5f, stationaryWarnThresholdSeconds))
            {
                Debug.LogWarning(snapshot, this);
                return;
            }

            Debug.Log(snapshot, this);
        }

        private string BuildBehaviorDebugSnapshot()
        {
            var navEnabled = navMeshAgent != null && navMeshAgent.enabled;
            var navOnMesh = navEnabled && navMeshAgent.isOnNavMesh;
            var navPathPending = navEnabled && navMeshAgent.pathPending;
            var navHasPath = navEnabled && navMeshAgent.hasPath;
            var navRemainingDistance = navEnabled ? navMeshAgent.remainingDistance : -1f;
            var navVelocity = navEnabled ? navMeshAgent.velocity.magnitude : 0f;

            var distanceToEntryExit = -1f;
            var distanceToNavmeshTargetExit = -1f;
            if (hasPendingExitPosition)
            {
                distanceToEntryExit = Vector2.Distance(
                    new Vector2(transform.position.x, transform.position.z),
                    new Vector2(pendingExitPosition.x, pendingExitPosition.z));
            }

            if (hasPendingNavmeshTargetPosition)
            {
                distanceToNavmeshTargetExit = Vector2.Distance(
                    new Vector2(transform.position.x, transform.position.z),
                    new Vector2(pendingNavmeshTargetPosition.x, pendingNavmeshTargetPosition.z));
            }

            var stateTag = ResolveBehaviorStateTag(
                distanceToEntryExit,
                distanceToNavmeshTargetExit,
                navEnabled,
                navOnMesh,
                navPathPending,
                navHasPath);
            return "[DecisionAgentPoint] Behavior snapshot"
                + " agent_id=" + NormalizeDebugValue(agentId)
                + " state=" + stateTag
                + " current_zone_id=" + NormalizeDebugValue(currentZoneId)
                + " needs_decision=" + needsLlmDecision
                + " chosen_exit_id=" + NormalizeDebugValue(lastChosenExitId)
                + " pending_exit_id=" + NormalizeDebugValue(pendingExitId)
                + " pending_navmesh_target_exit_id=" + NormalizeDebugValue(pendingNavmeshTargetExitId)
                + " pending_target_zone_id=" + NormalizeDebugValue(pendingTargetZoneId)
                + " has_pending_exit_position=" + hasPendingExitPosition
                + " has_pending_navmesh_target_position=" + hasPendingNavmeshTargetPosition
                + " moving_to_exit_before_navmesh=" + movingToExitBeforeNavMesh
                + " distance_to_entry_exit=" + distanceToEntryExit.ToString("F2")
                + " distance_to_navmesh_target_exit=" + distanceToNavmeshTargetExit.ToString("F2")
                + " stationary_seconds=" + stationaryDurationSeconds.ToString("F2")
                + " nav_enabled=" + navEnabled
                + " nav_on_mesh=" + navOnMesh
                + " nav_path_pending=" + navPathPending
                + " nav_path_pending_seconds=" + navPathPendingDurationSeconds.ToString("F2")
                + " nav_has_path=" + navHasPath
                + " nav_remaining_distance=" + navRemainingDistance.ToString("F2")
                + " nav_velocity=" + navVelocity.ToString("F2")
                + " last_move_message=" + NormalizeDebugValue(lastMoveMessage);
        }

        private string ResolveBehaviorStateTag(
            float distanceToEntryExit,
            float distanceToNavmeshTargetExit,
            bool navEnabled,
            bool navOnMesh,
            bool navPathPending,
            bool navHasPath)
        {
            if (needsLlmDecision && !hasPendingExitPosition && !hasPendingNavmeshTargetPosition)
            {
                return "waiting_decision_output";
            }

            if (hasPendingExitPosition || hasPendingNavmeshTargetPosition)
            {
                if (movingToExitBeforeNavMesh)
                {
                    return "pre_move_to_exit";
                }

                if (navMeshAgent == null)
                {
                    return "pending_exit_navmesh_missing";
                }

                if (!navEnabled)
                {
                    return "pending_exit_navmesh_disabled";
                }

                if (!navOnMesh)
                {
                    return "pending_exit_navmesh_offmesh";
                }

                if (navPathPending)
                {
                    return "pending_exit_path_pending";
                }

                if (navHasPath)
                {
                    return "moving_to_target_exit_navmesh";
                }

                if (distanceToEntryExit >= 0f && distanceToEntryExit <= Mathf.Max(0.05f, exitArriveDistance))
                {
                    return "near_exit_waiting_zone_transfer";
                }

                if (distanceToNavmeshTargetExit >= 0f && distanceToNavmeshTargetExit <= Mathf.Max(0.05f, exitArriveDistance))
                {
                    return "near_target_exit_waiting_zone_transfer";
                }

                return "pending_exit_no_active_path";
            }

            if (!needsLlmDecision)
            {
                return "idle_waiting_next_trigger";
            }

            return "unknown";
        }

        private static string NormalizeDebugValue(string value)
        {
            return string.IsNullOrWhiteSpace(value) ? "(empty)" : value.Trim();
        }

        private bool ShouldSuppressBehaviorDebugLogs()
        {
            ResolveSchedulerReference();
            return scheduler != null && scheduler.ShouldSuppressAgentBehaviorLogs;
        }

        private void ResolveSchedulerReference()
        {
            if (scheduler != null)
            {
                return;
            }

            if (!autoFindScheduler)
            {
                return;
            }

            scheduler = FindObjectOfType<DecisionBatchScheduler>();
        }

        private void TryReportAfterStateChanged()
        {
            if (!enableLegacySelfReporting)
            {
                return;
            }

            if (!isActiveAndEnabled)
            {
                return;
            }

            if (reportOnlyInPlayMode && !Application.isPlaying)
            {
                return;
            }

            ReportToSchedulerNow();
        }

        private string BuildDilemmaSummary(
            string normalizedCrowdType,
            string normalizedZoneId,
            List<DecisionAvailableExitOptionDto> exits,
            string normalizedAlgorithmRecommendation)
        {
            // 人物类型（优先使用模板中的 display_name）
            var roleName = ResolveCrowdTypeDisplayName(normalizedCrowdType);

            // 当前区域名称（优先使用拓扑中的 zone_name）
            var zoneDisplayName = normalizedZoneId;
            if (topologySceneConfig != null
                && topologySceneConfig.TryGetZoneById(normalizedZoneId, out var currentZone)
                && currentZone != null
                && !string.IsNullOrWhiteSpace(currentZone.zone_name))
            {
                zoneDisplayName = currentZone.zone_name;
            }

            // 停留时间（毫秒 → 秒，保留 1 位小数）
            var stayMs = Mathf.RoundToInt(Mathf.Max(0f, Time.unscaledTime - zoneEnterTime) * 1000f);
            var staySeconds = stayMs / 1000f;
            var stayText = staySeconds.ToString("F1") + "秒";

            // 耐心消耗语义标签 + 百分比（对齐后端 patience_ratio_display 规则）
            var patiencePercent = Mathf.RoundToInt(Mathf.Clamp01(patienceRatio) * 100f);
            var patienceText = ResolvePatienceRatioLabel(patienceRatio) + "(" + patiencePercent + "%)";

            // 偏好地点类型（从算法推荐出口解析目标 zone 的类型）
            var preferenceText = "未知区域";
            if (!string.IsNullOrWhiteSpace(normalizedAlgorithmRecommendation) && exits != null && exits.Count > 0)
            {
                var recommendedExit = exits.Find(
                    e => e != null
                        && string.Equals(e.exit_id, normalizedAlgorithmRecommendation, StringComparison.OrdinalIgnoreCase));
                if (recommendedExit != null && !string.IsNullOrWhiteSpace(recommendedExit.target_zone_id))
                {
                    if (topologySceneConfig != null
                        && topologySceneConfig.TryGetZoneById(recommendedExit.target_zone_id, out var targetZone)
                        && targetZone != null
                        && !string.IsNullOrWhiteSpace(targetZone.zone_type))
                    {
                        preferenceText = ResolveZoneTypeDisplayName(targetZone.zone_type);
                    }
                }
            }

            return $"{roleName}已在{zoneDisplayName}停留{stayText}(耐心消耗{patienceText}), 偏好{preferenceText}, 当前面临出口选择困境。";
        }

        private static string ResolveZoneTypeDisplayName(string zoneTypeRaw)
        {
            if (string.IsNullOrWhiteSpace(zoneTypeRaw))
            {
                return "未知区域";
            }

            if (ZoneTypeMapper.TryParse(zoneTypeRaw, out var zoneType))
            {
                switch (zoneType)
                {
                    case ZoneType.Passage:
                        return "通道";
                    case ZoneType.Plaza:
                        return "广场";
                    case ZoneType.Exhibit:
                        return "展览区";
                    case ZoneType.Rest:
                        return "休息区";
                    case ZoneType.Commercial:
                        return "商业区";
                    case ZoneType.Service:
                        return "服务区";
                    case ZoneType.ExitFinal:
                        return "出口";
                    default:
                        return "其他区域";
                }
            }

            return zoneTypeRaw.Trim();
        }

        private static string ResolveCrowdTypeDisplayName(string normalizedCrowdType)
        {
            if (string.IsNullOrWhiteSpace(normalizedCrowdType))
            {
                return "一位人物";
            }

            var manager = ExperimentManager.ActiveInstance;
            if (manager != null)
            {
                var templates = manager.GetRuntimeCrowdTypeTemplatesSnapshot();
                if (templates != null)
                {
                    for (var i = 0; i < templates.Length; i++)
                    {
                        var template = templates[i];
                        if (template == null)
                        {
                            continue;
                        }

                        if (string.Equals(
                                (template.type_id ?? string.Empty).Trim(),
                                normalizedCrowdType,
                                StringComparison.OrdinalIgnoreCase))
                        {
                            if (!string.IsNullOrWhiteSpace(template.display_name))
                            {
                                return template.display_name.Trim();
                            }

                            break;
                        }
                    }
                }
            }

            // 回退：如果没有匹配的模板，返回原 ID（保证不是空字符串）
            return normalizedCrowdType;
        }

        private static Dictionary<string, CrowdTypeAttractionWeightsDto> ResolveCrowdTypeAttractionWeights()
        {
            var result = new Dictionary<string, CrowdTypeAttractionWeightsDto>(StringComparer.OrdinalIgnoreCase);
            var manager = ExperimentManager.ActiveInstance;
            if (manager != null)
            {
                var templates = manager.GetRuntimeCrowdTypeTemplatesSnapshot();
                if (templates != null)
                {
                    for (var i = 0; i < templates.Length; i++)
                    {
                        var template = templates[i];
                        if (template == null || string.IsNullOrWhiteSpace(template.type_id))
                        {
                            continue;
                        }

                        var typeId = template.type_id.Trim();
                        result[typeId] = template.attraction_weights != null
                            ? template.attraction_weights.Clone()
                            : CrowdTypeAttractionWeightsDto.CreateDefault();
                    }
                }
            }

            return result;
        }

        private Dictionary<string, int> BuildZoneArrivedCountMap()
        {
            var result = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
            ResolveTopologySceneConfig();
            if (topologySceneConfig == null)
            {
                return result;
            }

            TopologyUpsertRequestDto topologyRequest;
            string error;
            if (topologySceneConfig.TryBuildTopologyRequest(out topologyRequest, out error)
                && topologyRequest != null
                && topologyRequest.zones != null)
            {
                for (var i = 0; i < topologyRequest.zones.Length; i++)
                {
                    var zone = topologyRequest.zones[i];
                    if (zone == null || string.IsNullOrWhiteSpace(zone.zone_id))
                    {
                        continue;
                    }

                    var zoneId = zone.zone_id.Trim();
                    result[zoneId] = topologySceneConfig.GetZoneArrivedCount(zoneId);
                }
            }

            return result;
        }

        private static string ResolvePatienceRatioLabel(float ratio)
        {
            if (ratio < 0.5f)
            {
                return "较低，不太着急";
            }

            if (ratio <= 0.8f)
            {
                return "中等，开始有些焦虑";
            }

            if (ratio <= 1.0f)
            {
                return "较高，比较急迫";
            }

            return "已超出容忍限度，非常急迫";
        }

        private List<DecisionAvailableExitOptionDto> BuildAvailableExits()
        {
            var options = new List<DecisionAvailableExitOptionDto>();
            if (availableExits == null)
            {
                AppendAutoGeneratedExitsFromTopology(options);
                return options;
            }

            for (var i = 0; i < availableExits.Length; i++)
            {
                var config = availableExits[i];
                if (config == null)
                {
                    continue;
                }

                DecisionAvailableExitOptionDto dto;
                if (config.TryBuildDto(out dto) && dto != null)
                {
                    options.Add(dto);
                }
            }

            AppendAutoGeneratedExitsFromTopology(options);

            EnrichExitOptionsFromMapConfig(options);

            return options;
        }

        private void EnrichExitOptionsFromMapConfig(List<DecisionAvailableExitOptionDto> exits)
        {
            if (exits == null || exits.Count <= 0)
            {
                return;
            }

            ResolveTopologySceneConfig();
            if (topologySceneConfig == null)
            {
                return;
            }

            var zoneCapacityById = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
            var zoneTypeById = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            var topologyExitById = new Dictionary<string, TopologyExitDto>(StringComparer.OrdinalIgnoreCase);

            topologySceneConfig.BuildLookupMaps(zoneCapacityById, zoneTypeById, topologyExitById);

            LocalCrowdDecisionEngine.EnrichExitOptionsWithMapScores(
                exits,
                transform.position,
                crowdType,
                zoneCapacityById,
                zoneTypeById,
                topologyExitById,
                crowdTypeAttractionWeightsByTypeId: ResolveCrowdTypeAttractionWeights());
        }

        private void ResolveTopologySceneConfig()
        {
            if (topologySceneConfig != null)
            {
                return;
            }

            topologySceneConfig = FindObjectOfType<TopologySceneConfig>();
            if (topologySceneConfig != null)
            {
                return;
            }

            var candidates = FindObjectsOfType<TopologySceneConfig>(true);
            if (candidates != null && candidates.Length > 0)
            {
                topologySceneConfig = candidates[0];
            }
        }

        private void EnsureRenderersVisibleForMovementStart()
        {
            SetRenderersVisible(true);
            initialWaitingGateActive = false;
            rendererHiddenByFinalExitZone = false;
        }

        private void SyncRendererVisibilityByCurrentZone()
        {
            if (!hideRendererWhenInFinalExitZone)
            {
                if (rendererHiddenByFinalExitZone && !initialWaitingGateActive)
                {
                    SetRenderersVisible(true);
                }

                rendererHiddenByFinalExitZone = false;
                return;
            }

            if (!IsCurrentZoneFinalExit())
            {
                if (rendererHiddenByFinalExitZone && !initialWaitingGateActive)
                {
                    SetRenderersVisible(true);
                }

                rendererHiddenByFinalExitZone = false;
                return;
            }

            SetRenderersVisible(false);
            rendererHiddenByFinalExitZone = true;
        }

        private bool IsCurrentZoneFinalExit()
        {
            var normalizedZoneId = string.IsNullOrWhiteSpace(currentZoneId)
                ? string.Empty
                : currentZoneId.Trim();
            if (string.IsNullOrWhiteSpace(normalizedZoneId))
            {
                return false;
            }

            ResolveTopologySceneConfig();
            if (topologySceneConfig == null)
            {
                return false;
            }

            TopologyZoneDto zone;
            if (!topologySceneConfig.TryGetZoneById(normalizedZoneId, out zone)
                || zone == null
                || string.IsNullOrWhiteSpace(zone.zone_type))
            {
                return false;
            }

            ZoneType zoneType;
            if (ZoneTypeMapper.TryParse(zone.zone_type, out zoneType))
            {
                return zoneType == ZoneType.ExitFinal;
            }

            return string.Equals(zone.zone_type.Trim(), "exit_final", StringComparison.OrdinalIgnoreCase);
        }

        private void AppendAutoGeneratedExitsFromTopology(List<DecisionAvailableExitOptionDto> options)
        {
            if (!autoBuildAvailableExitsFromTopology || options == null)
            {
                return;
            }

            ResolveTopologySceneConfig();
            if (topologySceneConfig == null)
            {
                return;
            }

            TopologyUpsertRequestDto topologyRequest;
            string error;
            if (!topologySceneConfig.TryBuildTopologyRequest(out topologyRequest, out error)
                || topologyRequest == null
                || topologyRequest.zones == null
                || topologyRequest.zones.Length <= 0)
            {
                return;
            }

            var normalizedCurrentZoneId = string.IsNullOrWhiteSpace(currentZoneId) ? string.Empty : currentZoneId.Trim();
            var normalizedRecommendation = string.IsNullOrWhiteSpace(algorithmRecommendation)
                ? string.Empty
                : algorithmRecommendation.Trim();

            var addedExitIds = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            for (var i = 0; i < options.Count; i++)
            {
                var existing = options[i];
                if (existing == null || string.IsNullOrWhiteSpace(existing.exit_id))
                {
                    continue;
                }

                addedExitIds.Add(existing.exit_id.Trim());
            }

            for (var i = 0; i < topologyRequest.zones.Length; i++)
            {
                var zone = topologyRequest.zones[i];
                if (zone == null || string.IsNullOrWhiteSpace(zone.zone_id))
                {
                    continue;
                }

                TryAddZoneAsDecisionOption(
                    options,
                    addedExitIds,
                    zone.zone_id,
                    normalizedCurrentZoneId,
                    normalizedRecommendation);
            }
        }

        private bool TryAddZoneAsDecisionOption(
            List<DecisionAvailableExitOptionDto> options,
            HashSet<string> addedExitIds,
            string zoneId,
            string normalizedCurrentZoneId,
            string normalizedRecommendation)
        {
            if (options == null || addedExitIds == null || string.IsNullOrWhiteSpace(zoneId))
            {
                return false;
            }

            var normalizedExitId = zoneId.Trim();
            if (!string.IsNullOrWhiteSpace(normalizedCurrentZoneId)
                && string.Equals(normalizedExitId, normalizedCurrentZoneId, StringComparison.OrdinalIgnoreCase))
            {
                return false;
            }

            if (!addedExitIds.Add(normalizedExitId))
            {
                return false;
            }

            var baseScore = Mathf.Clamp01(autoGeneratedExitScore);

            var score = string.Equals(normalizedExitId, normalizedRecommendation, StringComparison.OrdinalIgnoreCase)
                ? 1f
                : baseScore;

            options.Add(new DecisionAvailableExitOptionDto
            {
                exit_id = normalizedExitId,
                target_zone_id = normalizedExitId,
                algorithm_score = score,
                nl_description = "Auto generated from topology zones.",
            });

            return true;
        }
