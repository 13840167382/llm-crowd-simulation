        public bool TryBuildDecisionRequest(out DecisionAgentRequestDto request, out string error)
        {
            ResolveTopologySceneConfig();
            var topologyVersion = topologySceneConfig != null ? topologySceneConfig.TopologyVersion : -1;
            if (!decisionRequestCacheDirty
                && cachedDecisionRequestTopologyVersion == topologyVersion)
            {
                request = cachedDecisionRequest;
                error = cachedDecisionRequestError;
                return cachedDecisionRequestValid;
            }

            var normalizedAgentId = string.IsNullOrWhiteSpace(agentId) ? string.Empty : agentId.Trim();
            var normalizedCrowdType = string.IsNullOrWhiteSpace(crowdType) ? string.Empty : crowdType.Trim();
            var normalizedZoneId = string.IsNullOrWhiteSpace(currentZoneId) ? string.Empty : currentZoneId.Trim();
            if (string.IsNullOrWhiteSpace(normalizedAgentId)
                || string.IsNullOrWhiteSpace(normalizedCrowdType)
                || string.IsNullOrWhiteSpace(normalizedZoneId))
            {
                request = null;
                error = "DecisionAgentPoint has invalid identity fields.";
                CacheDecisionRequest(request, error, false, topologyVersion);
                return false;
            }

            var exits = BuildAvailableExits();
            if (exits.Count <= 0)
            {
                request = null;
                error = "DecisionAgentPoint has no valid available exits. agent_id=" + normalizedAgentId;
                CacheDecisionRequest(request, error, false, topologyVersion);
                return false;
            }

            var normalizedAlgorithmRecommendation = NormalizeAlgorithmRecommendation(algorithmRecommendation, exits);

            var dynamicSummary = BuildDilemmaSummary(normalizedCrowdType, normalizedZoneId, exits, normalizedAlgorithmRecommendation);

            var currentStayMs = Mathf.RoundToInt(Mathf.Max(0f, Time.unscaledTime - zoneEnterTime) * 1000f);

            request = new DecisionAgentRequestDto
            {
                agent_id = normalizedAgentId,
                crowd_type = normalizedCrowdType,
                current_zone_id = normalizedZoneId,
                stay_duration_ms = currentStayMs,
                patience_ratio = Mathf.Max(0f, patienceRatio),
                algorithm_recommendation = normalizedAlgorithmRecommendation,
                dilemma_summary = string.IsNullOrWhiteSpace(dynamicSummary)
                    ? (string.IsNullOrWhiteSpace(dilemmaSummary) ? "No dilemma summary" : dilemmaSummary.Trim())
                    : dynamicSummary,
                available_exits = exits.ToArray(),
            };

            error = string.Empty;
            CacheDecisionRequest(request, error, true, topologyVersion);
            return true;
        }

        public bool TryBuildTrajectoryPoint(out TrajectoryPointIngestItemDto point)
        {
            var normalizedAgentId = string.IsNullOrWhiteSpace(agentId) ? string.Empty : agentId.Trim();
            var normalizedCrowdType = string.IsNullOrWhiteSpace(crowdType) ? string.Empty : crowdType.Trim();
            var normalizedZoneId = string.IsNullOrWhiteSpace(currentZoneId) ? string.Empty : currentZoneId.Trim();
            if (string.IsNullOrWhiteSpace(normalizedAgentId)
                || string.IsNullOrWhiteSpace(normalizedCrowdType)
                || string.IsNullOrWhiteSpace(normalizedZoneId))
            {
                point = null;
                return false;
            }

            ResolveNavMeshAgent();
            var speed = 0f;
            var isMovingByNavMesh = false;
            if (navMeshAgent != null && navMeshAgent.enabled && navMeshAgent.isOnNavMesh)
            {
                speed = Mathf.Max(0f, navMeshAgent.velocity.magnitude);
                isMovingByNavMesh = navMeshAgent.pathPending
                    || navMeshAgent.hasPath
                    || speed > 0.05f;
            }

            var isTransitioning = movingToExitBeforeNavMesh
                || hasPendingExitPosition
                || hasPendingNavmeshTargetPosition;

            var state = AgentState.Idle;
            if (isTransitioning)
            {
                state = AgentState.Transitioning;
            }
            else if (isMovingByNavMesh)
            {
                state = AgentState.Walking;
            }
            else if (needsLlmDecision)
            {
                state = AgentState.Queuing;
            }

            var targetExitId = string.Empty;
            if (!string.IsNullOrWhiteSpace(pendingNavmeshTargetExitId))
            {
                targetExitId = pendingNavmeshTargetExitId.Trim();
            }
            else if (!string.IsNullOrWhiteSpace(pendingExitId))
            {
                targetExitId = pendingExitId.Trim();
            }
            else if (!string.IsNullOrWhiteSpace(lastChosenExitId))
            {
                targetExitId = lastChosenExitId.Trim();
            }

            point = new TrajectoryPointIngestItemDto
            {
                agent_id = normalizedAgentId,
                crowd_type = normalizedCrowdType,
                position = new Position2DDto
                {
                    x = transform.position.x,
                    z = transform.position.z,
                },
                zone_id = normalizedZoneId,
                speed = speed,
                state = state.ToApiValue(),
                target_exit_id = string.IsNullOrWhiteSpace(targetExitId) ? null : targetExitId,
                is_queuing = state == AgentState.Queuing,
            };
            return true;
        }

