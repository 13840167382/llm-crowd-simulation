        public void SetOverrideZoneStartIndex(int currentZoneIndex)
        {
            var zones = OverrideZoneIds;
            if (zones.Length <= 0)
            {
                overrideZoneCurrentIndex = 0;
                return;
            }

            // 当前在 currentZoneIndex，下一目标为其下一个区域
            var normalizedIdx = ((currentZoneIndex % zones.Length) + zones.Length) % zones.Length;
            overrideZoneCurrentIndex = (normalizedIdx + 1) % zones.Length;
        }

        public bool TryResolveOverrideNextZone(out string nextZoneId, out string reasoning)
        {
            nextZoneId = string.Empty;
            reasoning = string.Empty;

            if (decisionOverrideMode == DecisionOverrideMode.Normal)
            {
                return false;
            }

            var zones = OverrideZoneIds;
            if (zones.Length <= 0)
            {
                return false;
            }

            if (decisionOverrideMode == DecisionOverrideMode.Random)
            {
                // 完全随机：排除当前区域（如果有多于 1 个可选区域）
                var pool = zones;
                var normalizedCurrent = (currentZoneId ?? string.Empty).Trim();
                if (zones.Length > 1 && !string.IsNullOrWhiteSpace(normalizedCurrent))
                {
                    var filtered = new List<string>();
                    for (var j = 0; j < zones.Length; j++)
                    {
                        if (!string.Equals((zones[j] ?? string.Empty).Trim(), normalizedCurrent, StringComparison.OrdinalIgnoreCase))
                        {
                            filtered.Add(zones[j]);
                        }
                    }

                    if (filtered.Count > 0)
                    {
                        pool = filtered.ToArray();
                    }
                }

                var randomIdx = UnityEngine.Random.Range(0, pool.Length);
                nextZoneId = pool[randomIdx];
                reasoning = $"random: picked zone (pool={pool.Length}) ({nextZoneId})";
                return true;
            }

            // FixedPath：跳过与当前区域相同的目标，推进到下一个不同区域
            var normalizedCurrentZone = (currentZoneId ?? string.Empty).Trim();
            var startIdx = overrideZoneCurrentIndex % zones.Length;
            var attempts = 0;
            var foundIdx = -1;
            while (attempts < zones.Length)
            {
                var candidateIdx = (startIdx + attempts) % zones.Length;
                var candidateZone = (zones[candidateIdx] ?? string.Empty).Trim();
                if (!string.IsNullOrWhiteSpace(normalizedCurrentZone)
                    && string.Equals(candidateZone, normalizedCurrentZone, StringComparison.OrdinalIgnoreCase))
                {
                    attempts++;
                    continue;
                }

                foundIdx = candidateIdx;
                break;
            }

            if (foundIdx < 0)
            {
                // 所有区域都是当前区域（极端情况），取下一个
                foundIdx = startIdx;
            }

            nextZoneId = zones[foundIdx];
            overrideZoneCurrentIndex = (foundIdx + 1) % zones.Length;
            reasoning = $"fixed_path: zone {overrideZoneCurrentIndex}/{zones.Length} (next: {nextZoneId})";
            return true;
        }

        public void ApplySpawnContext(string spawnedAgentId, string spawnedCrowdType, string spawnedZoneId, bool markNeedsDecision)
        {
            if (!string.IsNullOrWhiteSpace(spawnedAgentId))
            {
                agentId = spawnedAgentId.Trim();
            }

            if (!string.IsNullOrWhiteSpace(spawnedCrowdType))
            {
                crowdType = spawnedCrowdType.Trim();
            }

            if (!string.IsNullOrWhiteSpace(spawnedZoneId))
            {
                SetCurrentZone(spawnedZoneId.Trim());
            }

            needsLlmDecision = alwaysRequireLlmDecision || markNeedsDecision;
            InvalidateDecisionRequestCache();

            if (disableNavMeshInZone && !string.IsNullOrWhiteSpace(currentZoneId))
            {
                SetNavMeshEnabled(false);
            }

            TryApplyInitialWaitingGate();
            SyncRendererVisibilityByCurrentZone();

            TryReportAfterStateChanged();
        }

