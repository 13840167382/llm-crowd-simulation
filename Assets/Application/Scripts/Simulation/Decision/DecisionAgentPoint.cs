        private static string NormalizeAlgorithmRecommendation(
            string rawRecommendation,
            List<DecisionAvailableExitOptionDto> exits)
        {
            if (exits == null || exits.Count <= 0)
            {
                return null;
            }

            var normalized = string.IsNullOrWhiteSpace(rawRecommendation)
                ? string.Empty
                : rawRecommendation.Trim();

            var fallbackExitId = string.Empty;
            var fallbackScore = float.NegativeInfinity;

            for (var i = 0; i < exits.Count; i++)
            {
                var option = exits[i];
                if (option == null || string.IsNullOrWhiteSpace(option.exit_id))
                {
                    continue;
                }

                var normalizedExitId = option.exit_id.Trim();
                var score = option.algorithm_score;
                if (string.IsNullOrWhiteSpace(fallbackExitId)
                    || score > fallbackScore)
                {
                    fallbackExitId = normalizedExitId;
                    fallbackScore = score;
                }

                if (!string.IsNullOrWhiteSpace(normalized)
                    && string.Equals(normalizedExitId, normalized, StringComparison.OrdinalIgnoreCase))
                {
                    return normalizedExitId;
                }
            }

            return fallbackExitId;
        }

        public void ApplyDecisionResult(DecisionResultItemDto result)
        {
            if (result == null)
            {
                return;
            }

            var resultAgentId = string.IsNullOrWhiteSpace(result.agent_id) ? string.Empty : result.agent_id.Trim();
            if (!IsDecisionResultForThisAgent(resultAgentId))
            {
                return;
            }

            ReleaseInitialWaitingGateForFirstDecision();

            lastChosenExitId = string.IsNullOrWhiteSpace(result.chosen_exit_id) ? string.Empty : result.chosen_exit_id.Trim();
            lastDecisionSource = string.IsNullOrWhiteSpace(result.decision_source) ? string.Empty : result.decision_source.Trim();
            lastReasoning = string.IsNullOrWhiteSpace(result.reasoning) ? string.Empty : result.reasoning.Trim();
            lastConfidence = result.confidence;
            lastDecisionAtUnixMs = RequestIdUtility.GetUnixTimestampMs();

            if (!string.IsNullOrWhiteSpace(lastChosenExitId))
            {
                algorithmRecommendation = lastChosenExitId;
                InvalidateDecisionRequestCache();
            }

            if (enableBehaviorDebugLogs && Application.isPlaying && !ShouldSuppressBehaviorDebugLogs())
            {
                Debug.Log(
                    "[DecisionAgentPoint] Decision received"
                    + " agent_id=" + NormalizeDebugValue(agentId)
                    + " chosen_exit_id=" + NormalizeDebugValue(lastChosenExitId)
                    + " source=" + NormalizeDebugValue(lastDecisionSource)
                    + " confidence=" + lastConfidence.ToString("F2")
                    + " reasoning=" + NormalizeDebugValue(lastReasoning),
                    this);
            }

            TryMoveToLlmChosenExit(lastChosenExitId);

            needsLlmDecision = alwaysRequireLlmDecision;
            TryReportAfterStateChanged();
        }

