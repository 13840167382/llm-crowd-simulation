        [ContextMenu("Report Agent State To Scheduler")]
        public void ReportToSchedulerNow()
        {
            ResolveSchedulerReference();
            if (scheduler == null)
            {
                lastReportMessage = "Report skipped: scheduler is missing.";
                return;
